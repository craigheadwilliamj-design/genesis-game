#!/usr/bin/env python3
"""Pack every PNG under sprites/ into js/spritepack.js (data URIs keyed by path).
The published artifact is capped at 511 files, so the game publishes this one file instead of ~480 PNGs.
Run it after adding or changing any sprite, then publish js/spritepack.js (and the JS you changed). Never edit the output by hand."""
import base64, json, os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
os.chdir(root)
pack = {}
for d, _, fs in os.walk("sprites"):
    for f in sorted(fs):
        if f.lower().endswith(".png"):
            p = os.path.join(d, f).replace(os.sep, "/")
            pack[p] = "data:image/png;base64," + base64.b64encode(open(p, "rb").read()).decode()
head = """// GENERATED by tools/packsprites.py from sprites/**/*.png: do not edit. Every sprite as a data URI, keyed by its path.
// spriteUrl(path) is what every drawn <image> and <img> uses (a short blob: URL once blobs are known to load, else the data URI itself).
const SPRITE_PACK = """
tail = """;
const spriteUrl = (() => {
  const cache = new Map(); let blobs = false;
  const toBlob = d => { const b = atob(d.slice(22)), u = new Uint8Array(b.length); for(let i = 0; i < b.length; i++) u[i] = b.charCodeAt(i); return URL.createObjectURL(new Blob([u], {type:"image/png"})); };
  // Blob URLs keep the drawn markup short; if the page can't load them, stay on data URIs
  try {
    const t = SPRITE_PACK[Object.keys(SPRITE_PACK)[0]], im = new Image(), u = toBlob(t);
    im.onload = () => { blobs = true; cache.clear(); }; im.src = u;
  } catch(e){}
  // the path rides along as a #fragment (ignored when loading) so the markup still says which picture it is
  const url = p => { const d = SPRITE_PACK[p]; if(!d) return p; if(!blobs) return d + "#" + p; let u = cache.get(p); if(!u){ try { u = toBlob(d) + "#" + p; } catch(e){ u = d + "#" + p; } cache.set(p, u); } return u; };
  // the pixel editor's "Try in park": a new picture for a path until reload
  url.swap = (p, d) => { SPRITE_PACK[p] = d; cache.delete(p); };
  return url;
})();
// Flat tiles in index.html (<pattern><image data-sp="sprites/...">) are swapped once the page has loaded
document.querySelectorAll("image[data-sp]").forEach(el => el.setAttribute("href", spriteUrl(el.dataset.sp)));
"""
open("js/spritepack.js", "w").write(head + json.dumps(pack, separators=(",", ":")) + tail)
print(len(pack), "sprites,", os.path.getsize("js/spritepack.js") // 1024, "KB")
